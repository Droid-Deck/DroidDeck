// Compile with the installed SDK's headers to verify the two mode vocabularies.
#include "viture_protocol_public.h"
#include "../../main/cpp/viture/display_modes.h"
using namespace droiddeck::viture;

#define CHECK_MODE(standard, native) \
    static_assert(to_native_mode(standard) == native); \
    static_assert(from_native_mode(native) == standard)
CHECK_MODE(VITURE_DISPLAY_MODE_1920_1080_60HZ, VITURE_NATIVE_DISPLAY_MODE_1920_1080_60HZ);
CHECK_MODE(VITURE_DISPLAY_MODE_1920_1080_90HZ, VITURE_NATIVE_DISPLAY_MODE_1920_1080_90HZ);
CHECK_MODE(VITURE_DISPLAY_MODE_1920_1080_120HZ, VITURE_NATIVE_DISPLAY_MODE_1920_1080_120HZ);
CHECK_MODE(VITURE_DISPLAY_MODE_3840_1080_60HZ, VITURE_NATIVE_DISPLAY_MODE_3D_SBS_3840_1080_60HZ);
CHECK_MODE(VITURE_DISPLAY_MODE_3840_1080_90HZ, VITURE_NATIVE_DISPLAY_MODE_3D_SBS_3840_1080_90HZ);
CHECK_MODE(VITURE_DISPLAY_MODE_1920_1200_60HZ, VITURE_NATIVE_DISPLAY_MODE_1920_1200_60HZ);
CHECK_MODE(VITURE_DISPLAY_MODE_1920_1200_90HZ, VITURE_NATIVE_DISPLAY_MODE_1920_1200_90HZ);
CHECK_MODE(VITURE_DISPLAY_MODE_1920_1200_120HZ, VITURE_NATIVE_DISPLAY_MODE_1920_1200_120HZ);
CHECK_MODE(VITURE_DISPLAY_MODE_3840_1200_60HZ, VITURE_NATIVE_DISPLAY_MODE_3D_SBS_3840_1200_60HZ);
CHECK_MODE(VITURE_DISPLAY_MODE_3840_1200_90HZ, VITURE_NATIVE_DISPLAY_MODE_3D_SBS_3840_1200_90HZ);
static_assert(from_native_mode(VITURE_NATIVE_DISPLAY_MODE_ULTRAWIDE_3840_1080_60HZ) < 0);
static_assert(from_native_mode(VITURE_NATIVE_DISPLAY_MODE_ULTRAWIDE_3840_1200_90HZ) < 0);
static_assert(to_native_mode(0) < 0);
