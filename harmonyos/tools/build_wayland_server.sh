#!/usr/bin/env bash
#
# Builds libwayland-server for HarmonyOS 7 (aarch64, musl).
#
# Upstream DroidDeck ships a bionic prebuilt in
# app/src/main/cpp/waylandcomp/prebuilt/lib/. A bionic library cannot be
# loaded on HarmonyOS, so the server core has to be rebuilt against the
# OHOS NDK's musl. Wayland is plain C, so this is a mechanical rebuild.
#
# The result is installed into entry/libs/arm64-v8a/ together with the
# headers the compositor needs.
#
# Usage:
#   OHOS_SDK_HOME=/path/to/openharmony-sdk tools/build_wayland_server.sh
#
# Host requirements: a C compiler, expat (macOS ships it; Debian:
# apt install libexpat1-dev), curl and tar.

set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
work="${WORK_DIR:-${TMPDIR:-/tmp}/droiddeck-wayland}"

WAYLAND_VERSION="1.22.0"
LIBFFI_VERSION="3.4.6"

: "${OHOS_SDK_HOME:?set OHOS_SDK_HOME to the OpenHarmony SDK root}"
NDK="${OHOS_SDK_HOME}/native"
CC="${NDK}/llvm/bin/clang"
AR="${NDK}/llvm/bin/llvm-ar"

if [ ! -x "${CC}" ]; then
  echo "the OHOS NDK compiler was not found at ${CC}" >&2
  exit 1
fi

CROSS="-target aarch64-linux-ohos --sysroot=${NDK}/sysroot -D__MUSL__"
CFLAGS="${CROSS} -O2 -fPIC"

mkdir -p "${work}"

# --- wayland -------------------------------------------------------------
if [ ! -d "${work}/wayland" ]; then
  echo "==> fetching wayland ${WAYLAND_VERSION}"
  git clone --depth 1 --branch "${WAYLAND_VERSION}" \
    https://github.com/wayland-mirror/wayland.git "${work}/wayland"
fi

# --- wayland-scanner (host tool) ----------------------------------------
#
# The scanner has a libxml2 backend and an expat backend. The libxml2 one
# calls the push-parser API (XML_GetBuffer and friends), which libxml2
# 2.10 and later no longer export, so the expat backend is used here: it
# needs nothing beyond expat, which every build host already has.
echo "==> building wayland-scanner (expat backend)"
(
  cd "${work}/wayland/src"
  sed -e 's/@WAYLAND_VERSION_MAJOR@/1/' \
      -e 's/@WAYLAND_VERSION_MINOR@/22/' \
      -e 's/@WAYLAND_VERSION_MICRO@/0/' \
      -e 's/@WAYLAND_VERSION@/1.22.0/' \
      wayland-version.h.in > wayland-version.h
  "${CC_FOR_HOST:-cc}" -O2 -o "${work}/wayland-scanner" \
    scanner.c wayland-util.c -I. -lexpat
)

echo "==> generating the protocol sources"
mkdir -p "${work}/wayland/build-gen"
(
  cd "${work}/wayland"
  "${work}/wayland-scanner" -s server-header protocol/wayland.xml build-gen/wayland-server-protocol.h
  "${work}/wayland-scanner" -s server-header -c protocol/wayland.xml build-gen/wayland-server-protocol-core.h
  "${work}/wayland-scanner" -s public-code protocol/wayland.xml build-gen/wayland-protocol.c
)

# --- libffi for musl -----------------------------------------------------
#
# The OHOS NDK does not ship libffi and wayland's wl_closure marshalling
# needs it. libffi is built here from the release tarball, which already
# contains a generated configure; the headers are generated by hand
# because autoheader is not needed for a single target.
if [ ! -d "${work}/libffi-${LIBFFI_VERSION}" ]; then
  echo "==> fetching libffi ${LIBFFI_VERSION}"
  curl -sL -o "${work}/libffi.tar.gz" \
    "https://github.com/libffi/libffi/releases/download/v${LIBFFI_VERSION}/libffi-${LIBFFI_VERSION}.tar.gz"
  tar xf "${work}/libffi.tar.gz" -C "${work}"
fi

echo "==> building libffi for aarch64 musl"
(
  cd "${work}/libffi-${LIBFFI_VERSION}"
  mkdir -p build/include build/obj
  sed -e 's/@VERSION@/'"${LIBFFI_VERSION}"'/g' \
      -e 's/@TARGET@/AARCH64/g' \
      -e 's/@HAVE_LONG_DOUBLE@/1/g' \
      -e 's/@HAVE_LONG_DOUBLE_VARIANT@/0/g' \
      -e 's/@FFI_EXEC_TRAMPOLINE_TABLE@/0/g' \
      include/ffi.h.in > build/include/ffi.h
  cp src/arm/ffitarget.h build/include/ffitarget.h
  cat > fficonfig.h <<'CONFIG'
/* Hand written fficonfig.h for the HarmonyOS (musl, aarch64) build.
   autoheader would emit the same standard includes here. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define HAVE_MEMCPY 1
#define HAVE_MEMFD_CREATE 1
#define HAVE_MMAP 1
#define HAVE_MMAP_ANON 1
#define HAVE_MMAP_FILE 1
#define HAVE_UNISTD_H 1
#define HAVE_SYS_MMAN_H 1
#define HAVE_SYS_TYPES_H 1
#define HAVE_STDINT_H 1
#define HAVE_INTTYPES_H 1
#define HAVE_DLFCN_H 1
#define SIZEOF_DOUBLE 8
#define SIZEOF_LONG_DOUBLE 8
#define SIZEOF_SIZE_T 8
#define SIZEOF_LONG 8
#define SIZEOF_LONG_LONG 8
#define SIZEOF_INT 4
#define SIZEOF_SHORT 2
#define SIZEOF_WCHAR_T 4
#define STACK_DIRECTION -1
#define FFI_EXEC_TRAMPOLINE_TABLE 0
#if defined(__GNUC__) && (__GNUC__ >= 4)
#define FFI_HIDDEN __attribute__ ((visibility ("hidden")))
#else
#define FFI_HIDDEN
#endif
#define HAVE_HIDDEN_VISIBILITY_ATTRIBUTE 1
CONFIG
  for f in closures java_raw_api prep_cif raw_api types; do
    "${CC}" ${CFLAGS} -Ibuild/include -Iinclude -Isrc/arm -I. \
      -c "src/${f}.c" -o "build/obj/${f}.o"
  done
  "${AR}" rcs build/libffi.a build/obj/*.o
)

# --- libwayland-server ----------------------------------------------------
echo "==> building libwayland-server for aarch64 musl"
(
  cd "${work}/wayland"
  mkdir -p build-ohos/obj
  cp build-gen/wayland-server-protocol.h build-gen/wayland-server-protocol-core.h \
     build-gen/wayland-protocol.c build-ohos/
  cp src/wayland-version.h build-ohos/
  cat > build-ohos/config.h <<'CONFIG'
/* Configuration for the HarmonyOS (musl, aarch64) build of libwayland-server.

   musl has no <sys/ucred.h>; it provides struct ucred through
   <sys/socket.h> together with SO_PEERCRED, which is the branch
   wayland-os.c falls back to. The ucred defines must stay *undefined*
   rather than zero, because wayland-os.c tests them with #ifdef. */
#ifndef WAYLAND_CONFIG_H
#define WAYLAND_CONFIG_H

#define HAVE_ACCEPT4 1
#define HAVE_BROKEN_MSG_CMSG_CLOEXEC 0
#define HAVE_MEMFD_CREATE 1
#define HAVE_STRNDUP 1
#define HAVE_LIBXML 0

/* HAVE_SYS_UCRED_H and HAVE_XUCRED_CR_PID are intentionally not defined. */

#endif
CONFIG
  cp build-ohos/config.h config.h
  for f in wayland-server wayland-shm event-loop wayland-util connection wayland-os; do
    "${CC}" ${CFLAGS} -Ibuild-ohos -Isrc -I. \
      -I"${work}/libffi-${LIBFFI_VERSION}/build/include" \
      -c "src/${f}.c" -o "build-ohos/obj/${f}.o"
  done
  "${CC}" ${CFLAGS} -Ibuild-ohos -Isrc -I. \
    -I"${work}/libffi-${LIBFFI_VERSION}/build/include" \
    -c build-ohos/wayland-protocol.c -o build-ohos/obj/wayland-protocol.o
  # The SONAME has to match the file name the HAP ships, because the
  # loader resolves a DT_NEEDED entry by name against the app's library
  # directory. Upstream's own convention is libwayland-server.so.0, but
  # the file is installed as libwayland-server.so, so a .so.0 SONAME
  # would leave the dependency unresolvable on the device.
  "${CC}" ${CROSS} -shared -Wl,-soname,libwayland-server.so \
    -o build-ohos/libwayland-server.so.0.22.0 \
    build-ohos/obj/*.o \
    "${work}/libffi-${LIBFFI_VERSION}/build/libffi.a" -lm
)

# --- install -------------------------------------------------------------
echo "==> installing into the project"
mkdir -p "${root}/entry/libs/arm64-v8a"

# The headers the compositor compiles against are NOT installed here.
#
# entry/src/main/cpp/thirdparty/wayland/include/ holds upstream's
# wlroots-patched Wayland headers, which the ported compositor needs: the
# patch adds a `release` member to wl_data_device_manager_interface, and
# upstream's wl_clipboard.c initialises it. The stock headers generated from
# wayland.xml do not have that member, so overwriting them would stop the
# compositor from compiling.
#
# The library built above is the stock Wayland server core, which is fine:
# the patched member is the third one, and the stock server never dispatches
# a third request for that interface, so the extra handler is simply never
# called. The first two members, which the library does dispatch, are
# identical in both layouts.
#
# The headers are checked instead of replaced, so a mistake here fails
# loudly rather than quietly breaking the compositor.
echo "==> checking the vendored Wayland headers"
vendored="${root}/entry/src/main/cpp/thirdparty/wayland/include/wayland-server-protocol.h"
if [ ! -f "${vendored}" ]; then
  echo "the patched headers are missing: ${vendored}" >&2
  exit 1
fi
if ! grep -q '(\*release)' "${vendored}"; then
  echo "${vendored} is not the patched header upstream ships." >&2
  echo "Copy it from upstream's app/src/main/cpp/waylandcomp/prebuilt/include/." >&2
  exit 1
fi
echo "    the patched headers are in place"

cp "${work}/wayland/build-ohos/libwayland-server.so.0.22.0" \
   "${root}/entry/libs/arm64-v8a/libwayland-server.so"

echo "==> done: entry/libs/arm64-v8a/libwayland-server.so"
file "${root}/entry/libs/arm64-v8a/libwayland-server.so"
